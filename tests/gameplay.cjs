const assert=require('node:assert/strict');
require('../dist/gameplay.js');
const {analogVector,SequenceDance}=globalThis.MeydanGameplay;
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,`${a} != ${b}`);
assert.equal(analogVector(2,2,54).strength,0);
const a=analogVector(17,-37,54);
close(a.x/a.y,17/-37); // An arbitrary angle must not snap to cardinal/diagonal directions.
assert.ok(a.strength>0&&a.strength<1);
assert.ok(analogVector(17,-37,54).strength>analogVector(8.5,-18.5,54).strength);
close(analogVector(200,0,54).strength,1);
close(analogVector(200,0,54).thumbX,54);
const pattern=[0,1,3,2,0,2,1,3,0];
let game=new SequenceDance(120,[pattern,pattern,pattern,pattern],2);
assert.equal(game.confirm(.1),'incomplete');assert.deepEqual(game.takeResults(),[]);
assert.equal(game.press(0,.2),'correct');assert.equal(game.press(3,.3),'wrong');
assert.equal(game.position,0);
assert.deepEqual(game.lastReset,{reason:'wrong-direction',from:1,index:0});
game.press(0,.4);game.press(1,.5);assert.deepEqual(game.takeResults(),[]);
assert.equal(game.press(3,.55),'wrong'); // extra direction after completion resets too
assert.equal(game.position,0);
assert.deepEqual(game.lastReset,{reason:'extra-direction',from:2,index:0});
game.press(0,.6);game.press(1,.7);
assert.equal(game.confirm(game.target),'perfect');assert.equal(game.confirm(game.target),'inactive');
assert.deepEqual(game.takeResults(),[{kind:'perfect',index:0}]);
game.update(4);game.press(0,4.1);game.press(1,4.2);game.confirm(game.target);
assert.equal(game.level,2);game.update(8);assert.equal(game.directions.length,3);
game.press(0,8.1);game.press(1,8.2);game.press(3,8.3);
assert.equal(game.confirm(8.4),'miss');assert.equal(game.level,1);
assert.equal(game.confirm(8.5),'inactive');
game=new SequenceDance(96,[pattern,pattern,pattern],2);
game.update(100);assert.equal(game.done,true);
assert.deepEqual(game.takeResults().map(e=>e.index),[0,1,2]);
game.update(101);assert.deepEqual(game.takeResults(),[]);
game=new SequenceDance(96,[pattern],2,1);
assert.equal(game.press(0,0),'inactive');
console.log('PASS: analog angle/speed/deadzone/clamp; sequence order/retry; confirmation-only scoring; duplicate rejection; adaptive level; lag catch-up; offset.');
